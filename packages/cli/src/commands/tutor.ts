interface CardPlan {
  readonly spec: CultureCardSpec;
  readonly skillId: string | null;
  readonly existingId: string | null;
  readonly rendered: RenderedCard | null;
  readonly missing: readonly string[];
}

export const culture = Command.make("culture", { as: asActor, unit: unitOption }, ({ as, unit }) =>
  Effect.gen(function* () {
    const g = yield* molo;
    const unitSlug = Option.getOrUndefined(unit);
    const file = loadCultureCards();
    const specs = file.cards.filter((c) => !unitSlug || c.unitSlug === unitSlug);
    if (specs.length === 0 && unitSlug)
      return yield* fail(`curriculum/culture-cards.json has no cards for ${unitSlug}`);

    yield* withDb(g, (db) =>
      Effect.gen(function* () {
        const actor = yield* Effect.promise(() => editorActor(db, as));
        if (typeof actor === "string") return yield* fail(actor);
        const repo = tutorRepo(db, actor);
        const course = yield* Effect.promise(() => coursesRepo(db).defaultCourse());
        const skills = yield* Effect.promise(() => repo.skillsByKey(course?.id));
        const lexicon = yield* Effect.promise(() => lexiconFor(db));

        const plan: CardPlan[] = [];
        for (const spec of specs) {
          const skill = skills.get(`${spec.unitSlug}/${spec.skillSlug}`);
          const result = renderCultureCard(spec, lexicon);
          plan.push({
            spec,
            skillId: skill?.id ?? null,
            existingId: skill
              ? ((yield* Effect.promise(() =>
                  repo.findCultureCard(skill.id, spec.slug, spec.title.en),
                ))?.id ?? null)
              : null,
            rendered: result.ok ? result.card : null,
            missing: result.ok ? [] : result.missing,
          });
        }

        yield* out(
          g,
          {
            cards: plan.map((p) => ({
              card: p.spec.slug,
              skill: `${p.spec.unitSlug}/${p.spec.skillSlug}`,
              state: cardState(p),
              missingWords: p.missing,
              strayWords: p.rendered?.strayWords ?? [],
            })),
          },
          () => renderCards(plan),
        );

        const toWrite = plan.filter((p) => cardState(p) === "would write");
        if (toWrite.length === 0) {
          if (g.json !== true) console.log("\nnothing to write.");
          return;
        }
        const apply = yield* gate(
          g,
          `write ${toWrite.length} culture cards as ai_draft ` +
            `(nothing is published; each waits for the tutor to confirm its caveat)`,
        );
        if (!apply) return;

        const written: Array<{ card: string; id: string }> = [];
        for (const p of toWrite) {
          const id = yield* Effect.promise(() =>
            repo.addCultureCard({
              skillId: p.skillId as string,
              slug: p.spec.slug,
              payload: (p.rendered as RenderedCard).payload,
              caveat: p.spec.caveat,
            }),
          );
          written.push({ card: p.spec.slug, id });
        }
        yield* out(g, { written }, () => {
          console.log("\nwritten as ai_draft:");
          table(written);
          console.log(
            "\nNothing here is published. Each card waits in /edit/culture with its caveat:\n" +
              "the claims the tutor confirms or strikes before a second editor can approve it.",
          );
        });
      }),
    );
  }),
).pipe(
  Command.withDescription(
    "Load curriculum/culture-cards.json as ai_draft culture cards for the tutor to check (--live writes)",
  ),
);

function cardState(p: CardPlan): string {
  if (p.skillId === null) return "no such skill";
  if (p.missing.length > 0) return "refused: word not in lexicon";
  if (p.existingId !== null) return "already there";
  return "would write";
}

function renderCards(plan: readonly CardPlan[]): void {
  console.log(
    "culture cards (nothing here is published; every card enters as ai_draft with its caveat)\n",
  );
  table(
    plan.map((p) => ({
      card: p.spec.slug,
      skill: `${p.spec.unitSlug}/${p.spec.skillSlug}`,
      state: cardState(p),
      words: p.spec.words.length,
      claims: p.spec.caveat.split("\n").length,
    })),
  );
  const refused = plan.filter((p) => p.missing.length > 0);
  if (refused.length > 0) {
    console.log("\nrefused rather than guessed: these words are not in the lexicon");
    kv(Object.fromEntries(refused.map((p) => [p.spec.slug, p.missing.join(", ")])));
  }
  const stray = plan.filter((p) => (p.rendered?.strayWords.length ?? 0) > 0);
  if (stray.length > 0) {
    console.log(
      "\nlexicon words in the prose outside a {placeholder} (check each is really English or Norwegian):",
    );
    table(
      stray.flatMap((p) =>
        (p.rendered as RenderedCard).strayWords.map((s) => ({
          card: p.spec.slug,
          lang: s.lang,
          word: s.word,
        })),
      ),
    );
  }
}

/**
 * `molo content link-sentences`: link the words of the tutors' sentences to
 * the lexicon, as far as that needs no judgement (@molo/content
 * sentence-links). A word is linked only when its written form is a lemma or
 * an infinitive; a lemma is xh-morph-verified, an infinitive is not. The rest
 * is printed for an editor, with the request's words that appear inside an
 * unlinked word as hints. Only sentences with no links at all are touched, so
 * an editor's work is never overwritten; nothing is published.
 */
export const linkSentences = Command.make(
  "link-sentences",
  { as: asActor, unit: unitOption },
  ({ as, unit }) =>
    Effect.gen(function* () {
      const g = yield* molo;
      const unitSlug = Option.getOrUndefined(unit);
      yield* withDb(g, (db) =>
        Effect.gen(function* () {
          const actor = yield* Effect.promise(() => editorActor(db, as));
          if (typeof actor === "string") return yield* fail(actor);
          const sentences = yield* Effect.promise(() =>
            tutorRepo(db, actor).sentencesToLink(unitSlug),
          );
          const lexicon = yield* Effect.promise(() =>
            curationLexicon(db, "xh", { excludeRetired: true }),
          );
          const index = buildLexiconIndex(lexicon);
          const plans = sentences.map((s) => ({
            s,
            plan: planSentenceLinks(s.textXh, index, s.targetLexemeIds),
          }));

          yield* out(
            g,
            {
              sentences: plans.map(({ s, plan }) => ({
                sentenceId: s.sentenceId,
                skill: `${s.unitSlug}/${s.skillSlug}`,
                text: s.textXh,
                linked: plan.tokens.map((t) => ({ word: t.surfaceForm, verified: t.isLemma })),
                ambiguous: plan.ambiguous.map((a) => a.word),
                unlinked: plan.unlinked,
                requestedButUnused: plan.targetsUnused,
              })),
            },
            () => {
              if (plans.length === 0) {
                console.log("No tutor sentence is waiting for its words to be linked.");
                return;
              }
              for (const { s, plan } of plans) {
                console.log(`\n${s.unitSlug}/${s.skillSlug} · ${s.status}\n  ${s.textXh}`);
                const linked = plan.tokens.map(
                  (t) => `${t.surfaceForm}${t.isLemma ? " ✓" : " (infinitive)"}`,
                );
                if (linked.length > 0) console.log(`  link:      ${linked.join(", ")}`);
                if (plan.ambiguous.length > 0)
                  console.log(`  ambiguous: ${plan.ambiguous.map((a) => a.word).join(", ")}`);
                for (const u of plan.unlinked)
                  console.log(
                    `  for an editor: ${u.word}${u.hints.length > 0 ? `  (contains ${u.hints.join(", ")}?)` : ""}`,
                  );
              }
            },
          );

          const toWrite = plans.filter(({ plan }) => plan.tokens.length > 0);
          if (toWrite.length === 0) return;
          const apply = yield* gate(
            g,
            `link ${toWrite.reduce((n, p) => n + p.plan.tokens.length, 0)} words in ${toWrite.length} sentences ` +
              "(exact lemma or infinitive only; nothing is published, unlinked words stay for an editor)",
          );
          if (!apply) return;
          const repo = editorRepo(db, actor);
          for (const { s, plan } of toWrite) {
            yield* Effect.promise(() =>
              repo.setSentenceTokens(
                s.sentenceId,
                plan.tokens.map((t) => ({
                  position: t.position,
                  lexemeId: t.lexemeId,
                  surfaceForm: t.surfaceForm,
                  // The one case verify.ts calls verified without generating anything.
                  morphVerified: t.isLemma,
                  irregular: false,
                  irregularNote: null,
                })),
              ),
            );
          }
          if (g.json !== true)
            console.log(
              `\nlinked ${toWrite.length} sentences. Open each in /edit/sentences to finish the rest.`,
            );
        }),
      );
    }),
).pipe(
  Command.withDescription(
    "Link the words of tutor sentences to the lexicon where the form is a lemma or infinitive; the rest is listed for an editor (--live writes)",
  ),
);
